# ──────────────────────────── Helpers ────────────────────────────

def analyze_tgs_file(file_path):
    """Analyze a TGS file and print detailed information."""
    try:
        with rlottie.LottieAnimation.from_tgs(file_path) as anim:
            total_frames = anim.lottie_animation_get_totalframe()
            fps = anim.lottie_animation_get_framerate()
            duration = total_frames / fps if fps > 0 else 0

            print(f"    📁 Source    : {os.path.basename(file_path)}")
            print(f"    ⏱️  Original : {total_frames} frames @ {fps} FPS ({duration:.3f}s)")
            return total_frames, fps, duration
    except Exception as e:
        print(f"    ❌ Analysis failed: {e}")
        return None, None, None


def analyze_webp_output(file_path):
    """Analyze a WebP output file and print detailed information."""
    if not os.path.exists(file_path):
        print(f"    ❌ Output file not found: {file_path}")
        return False

    try:
        img = Image.open(file_path)
        size_bytes = os.path.getsize(file_path)

        print(f"    ✅ Output    : {os.path.basename(file_path)}")
        print(f"    📐 Resolution: {img.size[0]}x{img.size[1]}  |  Frames: {img.n_frames}  |  Size: {size_bytes:,} bytes ({size_bytes / 1024:.1f} KB)")
        print(f"    🎬 Format    : {img.format}, Animated: {img.is_animated}")

        if hasattr(img, 'info') and 'duration' in img.info:
            frame_dur = img.info['duration']
            eff_fps = 1000 / frame_dur if frame_dur > 0 else 0
            eff_dur = img.n_frames * frame_dur / 1000
            print(f"    🎯 Playback  : {eff_fps:.1f} FPS, {eff_dur:.3f}s duration")
        return True
    except Exception as e:
        print(f"    ❌ Output analysis failed: {e}")
        return False


def run_conversion(input_file, output_file, label="Converting", **kwargs):
    """Helper that times a conversion, prints results, and returns success."""
    print(f"    🔄 {label}...")
    start = time.time()
    success = convert_tgs_to_webp(input_file, output_file, **kwargs)
    elapsed = time.time() - start

    if success:
        print(f"    ⏱️  Done in {elapsed:.2f}s")
        analyze_webp_output(output_file)
    else:
        print(f"    ❌ Conversion failed after {elapsed:.2f}s")
    return success

